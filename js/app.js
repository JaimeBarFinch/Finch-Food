  if ('serviceWorker' in navigator && location.protocol !== 'file:') {
    navigator.serviceWorker.register('sw.js').then(function (reg) {
      function offer(sw) { toast('The menu has been updated.', 'Reload', function () { sw.postMessage('skipWaiting'); }); }
      if (reg.waiting && navigator.serviceWorker.controller) offer(reg.waiting);
      reg.addEventListener('updatefound', function () {
        var sw = reg.installing;
        sw.addEventListener('statechange', function () { if (sw.state === 'installed' && navigator.serviceWorker.controller) offer(sw); });
      });
    }).catch(function () { /* offline use just won't be available */ });
    /* reload when a NEW version takes over, but not on the very first visit, when there was no old version */
    var reloading = false, hadController = !!navigator.serviceWorker.controller;
    navigator.serviceWorker.addEventListener('controllerchange', function () {
      if (!hadController) { hadController = true; return; }
      if (!reloading) { reloading = true; location.reload(); }
    });
  }

